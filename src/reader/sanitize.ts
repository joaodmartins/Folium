import DOMPurify, { type Config } from 'dompurify';

/**
 * Book files are not trusted. This turns the HTML produced by markdown-it into a safe,
 * inert fragment that can be inserted in the page.
 *
 * - Only HTML elements are allowed (`USE_PROFILES: html`): no <svg>/<math> from authors.
 * - Scripts, event handlers (`onerror`…), `javascript:` URLs, iframes, objects, <style>
 *   and forms are removed by DOMPurify or by the lists below.
 * - `style`, `id`, `name` and `data-*` attributes are dropped: authors cannot restyle the
 *   page, spoof the app's own attributes, or clobber `document.*` properties through ids/names.
 *   The ids of headings are generated by Folium after sanitizing.
 */
const CONFIG: Config = {
  USE_PROFILES: { html: true },
  FORBID_TAGS: ['style', 'form', 'input', 'button', 'textarea', 'select', 'option', 'dialog'],
  FORBID_ATTR: ['style', 'id', 'name'],
  ALLOW_DATA_ATTR: false,
};

export function sanitizeHtml(html: string): DocumentFragment {
  const clean = DOMPurify.sanitize(html, CONFIG);
  // A <template> parses the HTML without running or loading anything until it is inserted.
  const template = document.createElement('template');
  template.innerHTML = clean;
  return template.content;
}
